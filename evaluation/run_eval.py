"""Offline, deterministic evaluation of the fictional clinic agent.

Run with::

    python -m evaluation.run_eval

It measures the retriever and the local role-aware responder against the gold
cases in ``cases.py`` and writes a human-readable report to
``evaluation/RESULTS.md`` plus machine-readable ``evaluation/results.json``.

No API key or network access is required: the default ``LocalTemplateEngine`` is
deterministic, so every run reproduces the same numbers. That is the whole
point -- the scores in the README can be regenerated by anyone.
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

from fictional_clinic.models import Role
from fictional_clinic.prompts import DISCLAIMER
from fictional_clinic.rag import LocalRetriever
from fictional_clinic.responder import LocalTemplateEngine

from evaluation.cases import IN_SCOPE, MORPHOLOGICAL, OUT_OF_SCOPE, RetrievalCase

HERE = Path(__file__).resolve().parent

# Headings each role's answer must contain (local engine, in-scope path).
REQUIRED_HEADINGS: dict[Role, list[str]] = {
    Role.patient: [
        "What this may mean",
        "What the clinic guide says",
        "Plain-language takeaways",
        "When to get help",
        "Recommendation",
        "Why this answer",
        "Questions to ask",
        "Safety note",
    ],
    Role.doctor: [
        "Clinical summary",
        "Retrieved protocol points",
        "Clinician-added context",
        "Clinical interpretation",
        "Evidence quality notes",
        "Recommendation",
        "Suggested reasoning",
        "Suggested next steps",
        "Limitations",
    ],
}

# Headings that must appear for one role and never leak into the other.
PATIENT_ONLY = {
    "What this may mean",
    "Plain-language takeaways",
    "When to get help",
    "Questions to ask",
    "Why this answer",
}
DOCTOR_ONLY = {
    "Clinical summary",
    "Retrieved protocol points",
    "Clinical interpretation",
    "Evidence quality notes",
    "Suggested reasoning",
    "Suggested next steps",
    "Limitations",
}

# Phrases that show the agent safely declined to fabricate a protocol.
ABSTENTION_PHRASES = (
    "could not find a relevant",
    "No evidence was retrieved",
    "do not have enough relevant evidence",
)


def _pct(part: int, whole: int) -> float:
    return round(100.0 * part / whole, 1) if whole else 0.0


def _top1_rate(retriever: LocalRetriever, cases: list[RetrievalCase]) -> float:
    hits = 0
    for case in cases:
        titles = [source.title for source in retriever.search(case.question)]
        if titles and titles[0] == case.expected_doc:
            hits += 1
    return _pct(hits, len(cases))


def evaluate() -> dict:
    """Run the full evaluation and return a metrics dictionary."""
    retriever = LocalRetriever(stem_terms=True)
    engine = LocalTemplateEngine()

    # --- Retrieval metrics (in-scope) ---
    top1_hits = 0
    recall3_hits = 0
    reciprocal_ranks = 0.0
    for case in IN_SCOPE:
        titles = [source.title for source in retriever.search(case.question)]
        if titles and titles[0] == case.expected_doc:
            top1_hits += 1
        if case.expected_doc in titles:
            recall3_hits += 1
            reciprocal_ranks += 1.0 / (titles.index(case.expected_doc) + 1)

    # --- Abstention (out-of-scope retrieval returns nothing) ---
    abstain_hits = sum(1 for case in OUT_OF_SCOPE if not retriever.search(case.question))

    # --- Responder metrics ---
    heading_ok = 0
    heading_total = 0
    separation_ok = 0
    separation_total = 0
    grounded_ok = 0
    grounded_total = 0
    disclaimer_ok = 0
    disclaimer_total = 0
    safe_abstain_ok = 0

    # In-scope: structure, role separation, grounding, disclaimer.
    for case in IN_SCOPE:
        sources = retriever.search(case.question)
        for role, required in REQUIRED_HEADINGS.items():
            answer = engine.answer(role, case.question, sources)

            heading_total += 1
            if all(heading in answer for heading in required):
                heading_ok += 1

            separation_total += 1
            foreign = DOCTOR_ONLY if role is Role.patient else PATIENT_ONLY
            if not any(heading in answer for heading in foreign):
                separation_ok += 1

            grounded_total += 1
            if case.expected_doc and case.expected_doc in answer:
                grounded_ok += 1

            disclaimer_total += 1
            if DISCLAIMER in answer:
                disclaimer_ok += 1

    # Out-of-scope: must keep the disclaimer AND visibly decline to fabricate.
    for case in OUT_OF_SCOPE:
        sources = retriever.search(case.question)
        for role in REQUIRED_HEADINGS:
            answer = engine.answer(role, case.question, sources)
            disclaimer_total += 1
            if DISCLAIMER in answer:
                disclaimer_ok += 1
            if any(phrase in answer for phrase in ABSTENTION_PHRASES):
                safe_abstain_ok += 1

    safe_abstain_total = len(OUT_OF_SCOPE) * len(REQUIRED_HEADINGS)

    # --- Ablation: does stemming actually help? Compare top-1 on the hard
    # morphological-variant slice with stemming off vs on. ---
    lexical = LocalRetriever(stem_terms=False)
    stemmed = LocalRetriever(stem_terms=True)

    return {
        "dataset": {
            "in_scope": len(IN_SCOPE),
            "paraphrase": sum(1 for c in IN_SCOPE if c.kind == "paraphrase"),
            "morphological": len(MORPHOLOGICAL),
            "out_of_scope": len(OUT_OF_SCOPE),
            "roles_tested": list(r.value for r in REQUIRED_HEADINGS),
        },
        "retrieval": {
            "top1_accuracy": _pct(top1_hits, len(IN_SCOPE)),
            "recall_at_3": _pct(recall3_hits, len(IN_SCOPE)),
            "mrr": round(reciprocal_ranks / len(IN_SCOPE), 3) if IN_SCOPE else 0.0,
            "out_of_scope_abstention": _pct(abstain_hits, len(OUT_OF_SCOPE)),
        },
        "stemming_ablation": {
            "lexical_top1_morphological": _top1_rate(lexical, MORPHOLOGICAL),
            "stemmed_top1_morphological": _top1_rate(stemmed, MORPHOLOGICAL),
            "lexical_top1_in_scope": _top1_rate(lexical, IN_SCOPE),
            "stemmed_top1_in_scope": _top1_rate(stemmed, IN_SCOPE),
        },
        "responder": {
            "heading_compliance": _pct(heading_ok, heading_total),
            "role_separation": _pct(separation_ok, separation_total),
            "answer_grounded_in_source": _pct(grounded_ok, grounded_total),
            "safety_disclaimer_present": _pct(disclaimer_ok, disclaimer_total),
            "safe_abstention_no_fabrication": _pct(safe_abstain_ok, safe_abstain_total),
        },
    }


def format_markdown(metrics: dict) -> str:
    ds = metrics["dataset"]
    ret = metrics["retrieval"]
    res = metrics["responder"]
    abl = metrics["stemming_ablation"]
    roles = ", ".join(ds["roles_tested"])
    return f"""# Evaluation Results

_Generated by `python -m evaluation.run_eval` on {date.today().isoformat()}._
_Fully deterministic and offline -- no API key or network access required, so these numbers are reproducible by anyone._

**Dataset:** {ds["in_scope"]} in-scope questions (including {ds["paraphrase"]} hard
paraphrases that drop the condition name) + {ds["out_of_scope"]} out-of-scope
questions, evaluated across roles: {roles}.

## Retrieval (RAG)

| Metric | Score |
| --- | --- |
| Top-1 accuracy | {ret["top1_accuracy"]}% |
| Recall@3 | {ret["recall_at_3"]}% |
| Mean Reciprocal Rank (MRR) | {ret["mrr"]} |
| Out-of-scope abstention | {ret["out_of_scope_abstention"]}% |

## Role-aware responder

| Metric | Score |
| --- | --- |
| Heading compliance (required sections present) | {res["heading_compliance"]}% |
| Role separation (no cross-role sections leak) | {res["role_separation"]}% |
| Answer grounded in retrieved source | {res["answer_grounded_in_source"]}% |
| Safety disclaimer present | {res["safety_disclaimer_present"]}% |
| Safe abstention on out-of-scope (no fabrication) | {res["safe_abstention_no_fabrication"]}% |

> **Out-of-scope abstention** means the retriever returns nothing for unrelated
> real-world questions (e.g. "What is the capital of France?") instead of
> forcing an irrelevant match. **Safe abstention** means the responder then says
> it has no evidence rather than inventing a protocol.

## Retrieval robustness: does stemming help? (ablation)

Top-1 accuracy with stemming **off vs on**, on {ds["morphological"]} hard
morphological-variant queries where the only linking term appears as a plural or
verb form (e.g. *coughing* vs *cough*, *interruptions* vs *interruption*).

| Slice | Lexical (no stemming) | + Stemming | Δ |
| --- | --- | --- | --- |
| Morphological variants | {abl["lexical_top1_morphological"]}% | **{abl["stemmed_top1_morphological"]}%** | +{round(abl["stemmed_top1_morphological"] - abl["lexical_top1_morphological"], 1)} |
| In-scope (no regression check) | {abl["lexical_top1_in_scope"]}% | {abl["stemmed_top1_in_scope"]}% | {round(abl["stemmed_top1_in_scope"] - abl["lexical_top1_in_scope"], 1)} |

Stemming recovers the hard cases without regressing the easy ones or weakening
out-of-scope abstention.
"""


def _print_table(metrics: dict) -> None:
    print("\n=== Fictional Clinic Agent -- Evaluation ===")
    for section in ("retrieval", "responder", "stemming_ablation"):
        print(f"\n[{section}]")
        for name, value in metrics[section].items():
            label = name.replace("_", " ")
            suffix = "" if name == "mrr" else "%"
            print(f"  {label:<42} {value}{suffix}")


def main() -> None:
    metrics = evaluate()
    _print_table(metrics)

    (HERE / "results.json").write_text(
        json.dumps(metrics, indent=2) + "\n", encoding="utf-8"
    )
    (HERE / "RESULTS.md").write_text(format_markdown(metrics), encoding="utf-8")
    print(f"\nWrote {HERE / 'results.json'}")
    print(f"Wrote {HERE / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
