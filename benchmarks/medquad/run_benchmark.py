"""Run the MedQuAD retrieval benchmark: BM25 (lexical) vs embeddings (semantic).

For each real medical question, both retrievers rank the answer passages; we
record where the *correct* passage lands and report Recall@k and MRR@10. Unlike
the fictional-clinic eval, these are real questions over a 1,500-passage corpus,
so the numbers are genuinely below 100% -- and the gap shows what semantic
retrieval buys over keyword matching.

    python -m benchmarks.medquad.run_benchmark

Requires the benchmark extras and an ingested corpus::

    pip install -e ".[benchmark]"
    python -m benchmarks.medquad.ingest --source <MedQuAD-clone>
"""

from __future__ import annotations

import json
import time
from datetime import date
from pathlib import Path

from fictional_clinic.semantic import DEFAULT_MODEL, SemanticRetriever

from benchmarks.medquad.lexical import BM25Index

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"
K = 10


def load_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        raise SystemExit(f"missing {path} -- run `python -m benchmarks.medquad.ingest` first")
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def _gold_rank(ranked_ids: list[str], gold: str) -> int | None:
    for position, doc_id in enumerate(ranked_ids, start=1):
        if doc_id == gold:
            return position
    return None


def _metrics(ranks: list[int | None]) -> dict:
    n = len(ranks)
    hit = [r for r in ranks if r is not None]
    return {
        "recall@1": round(sum(r <= 1 for r in hit) / n, 4),
        "recall@5": round(sum(r <= 5 for r in hit) / n, 4),
        "recall@10": round(sum(r <= 10 for r in hit) / n, 4),
        "mrr@10": round(sum(1.0 / r for r in hit) / n, 4),
    }


def evaluate() -> dict:
    corpus = load_jsonl(DATA / "corpus.jsonl")
    questions = load_jsonl(DATA / "questions.jsonl")
    ids = [c["id"] for c in corpus]
    texts = [c["text"] for c in corpus]

    t0 = time.time()
    bm25 = BM25Index(ids, texts)
    lex_ranks = [_gold_rank([d for d, _ in bm25.rank(q["question"], K)], q["gold_id"]) for q in questions]
    lex_secs = round(time.time() - t0, 1)

    t1 = time.time()
    semantic = SemanticRetriever(DEFAULT_MODEL, cache_dir=DATA / "emb_cache")
    semantic.index(ids, texts)
    sem_lists = semantic.rank_many([q["question"] for q in questions], K)
    sem_ranks = [_gold_rank([d for d, _ in lst], q["gold_id"]) for lst, q in zip(sem_lists, questions)]
    sem_secs = round(time.time() - t1, 1)

    wins = _semantic_wins(questions, corpus, lex_ranks, sem_ranks)
    return {
        "corpus_size": len(corpus),
        "queries": len(questions),
        "model": DEFAULT_MODEL,
        "lexical": _metrics(lex_ranks) | {"seconds": lex_secs},
        "semantic": _metrics(sem_ranks) | {"seconds": sem_secs},
        "examples_semantic_wins": wins,
    }


def _semantic_wins(questions, corpus, lex_ranks, sem_ranks, top=5) -> list[dict]:
    focus_by_id = {c["id"]: c["focus"] for c in corpus}
    cand = []
    for q, lr, sr in zip(questions, lex_ranks, sem_ranks):
        if sr and sr <= 3 and (lr is None or lr > 10):
            cand.append({
                "question": q["question"],
                "focus": focus_by_id.get(q["gold_id"], ""),
                "lexical_rank": "not found" if lr is None else lr,
                "semantic_rank": sr,
            })
    return cand[:top]


def format_markdown(m: dict) -> str:
    lex, sem = m["lexical"], m["semantic"]

    def delta(key: str) -> str:
        d = round((sem[key] - lex[key]) * 100, 1)
        return f"+{d}" if d >= 0 else f"{d}"

    rows = "\n".join(
        f"| {label} | {lex[key]:.3f} | **{sem[key]:.3f}** | {delta(key)} pts |"
        for label, key in [
            ("Recall@1", "recall@1"),
            ("Recall@5", "recall@5"),
            ("Recall@10", "recall@10"),
            ("MRR@10", "mrr@10"),
        ]
    )
    examples = "\n".join(
        f'| _{ex["question"]}_ | {ex["focus"]} | {ex["lexical_rank"]} | {ex["semantic_rank"]} |'
        for ex in m["examples_semantic_wins"]
    ) or "| _(none in this sample)_ | | | |"

    return f"""# MedQuAD Retrieval Benchmark — Lexical vs Semantic

_Generated by `python -m benchmarks.medquad.run_benchmark` on {date.today().isoformat()}._

Real medical questions from [MedQuAD](https://github.com/abachaa/MedQuAD)
(NIH / NCI / CDC sources). Each query must retrieve its own answer passage from a
corpus of **{m["corpus_size"]} real passages** ({m["queries"]} held-out queries).
These are real numbers — well below 100% — and the point is the **gap**.

| Metric | BM25 (lexical) | MiniLM (semantic) | Δ |
| --- | --- | --- | --- |
{rows}

Embedding model: `{m["model"]}`. Both retrievers share the same tokenizer/stemmer
for the lexical side; semantic encodes on CPU
(index+score: {sem["seconds"]}s vs lexical {lex["seconds"]}s).

## Where semantic wins

Real questions the keyword retriever ranked poorly (or missed) but the embedding
retriever put near the top — usually because the question and answer use
different words for the same concept:

| Question | Topic | BM25 rank | Semantic rank |
| --- | --- | --- | --- |
{examples}

> **Takeaway:** on a real, messy corpus the lexical retriever is a solid
> baseline, but semantic retrieval meaningfully improves recall — exactly the
> limitation the fictional-clinic eval flagged, now measured on real data.
"""


def main() -> None:
    metrics = evaluate()
    lex, sem = metrics["lexical"], metrics["semantic"]
    print(f"\nMedQuAD benchmark — {metrics['corpus_size']} passages, {metrics['queries']} queries")
    print(f"{'metric':<12}{'BM25':>10}{'semantic':>12}")
    for key in ("recall@1", "recall@5", "recall@10", "mrr@10"):
        print(f"{key:<12}{lex[key]:>10.3f}{sem[key]:>12.3f}")

    (DATA / "results.json").write_text(json.dumps(metrics, indent=2) + "\n", encoding="utf-8")
    (HERE / "RESULTS.md").write_text(format_markdown(metrics), encoding="utf-8")
    print(f"\nWrote {DATA / 'results.json'}")
    print(f"Wrote {HERE / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
